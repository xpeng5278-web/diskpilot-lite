'use strict';

const fs = require('node:fs');
const { once } = require('node:events');
/** Yield synthetic WizTree CSV text blocks for the requested row count. */
function* chunks(count = 1000000) {
  yield 'Generated by WizTree（合成测试数据）\r\nFile Name,Size,Allocated,Modified,Attributes,Files,Folders,额外列\r\n';
  const bases = [
    'C:\\Windows\\Temp',
    'C:\\Users\\小明\\AppData\\Local\\Temp',
    'C:\\Users\\小明\\Documents\\WeChat Files',
    'C:\\Users\\小明\\Documents\\Tencent Files',
    'C:\\Users\\小明\\Downloads',
    'C:\\Users\\小明\\Desktop',
    'C:\\Users\\小明\\AppData\\Roaming\\DingTalk',
    'C:\\项目\\node_modules',
    'C:\\Program Files\\工具',
    'C:\\Users\\小明\\Pictures',
    'C:\\$Recycle.Bin',
    'C:\\Users\\小明\\.npm'
  ];
  let block = '';
  for (let index = 0; index < count; index++) {
    const base = bases[index % bases.length];
    const isDirectory = index % 1000 === 0;
    block +=
      '"' +
      base +
      '\\' +
      (isDirectory ? '目录' + index + '\\' : '文件' + index + '.dat') +
      '",4096,4096,,0,0,0,测试\r\n';
    if (index % 4096 === 4095) {
      yield block;
      block = '';
    }
  }
  if (block) {
    yield block;
  }
}
/** Write a synthetic CSV, waiting for stream backpressure and completion. */
async function generate(filename, count = 1000000) {
  const output = fs.createWriteStream(filename);
  for (const chunk of chunks(count)) {
    if (!output.write(chunk)) {
      await once(output, 'drain');
    }
  }
  output.end();
  await once(output, 'finish');
}
if (require.main === module) {
  const filename = process.argv[2] || 'build/合成扫描.csv';
  fs.mkdirSync(require('node:path').dirname(filename), {
    recursive: true
  });
  generate(filename, Number(process.argv[3]) || 1000000)
    .then(() => console.log('合成 CSV 已生成：' + filename))
    .catch((error) => {
      console.error('生成失败：' + error.message);
      process.exitCode = 1;
    });
}
module.exports = {
  chunks,
  generate
};
